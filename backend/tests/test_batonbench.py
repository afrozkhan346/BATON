import pytest
from batonbench.score import load_ground_truth, score_approach
from batonbench.baselines import (
    run_baseline_a_manual,
    run_baseline_b_generic_ai,
)
from batonbench.run import run_batonbench, generate_markdown_table


def test_ground_truth_integrity():
    gt = load_ground_truth()
    assert gt["project_name"] == "Inventory Service"
    assert len(gt["expected_facts"]) >= 5
    assert len(gt["known_gaps"]) >= 3
    assert len(gt["known_conflicts"]) >= 1
    assert len(gt["restricted_facts"]) >= 1
    assert len(gt["successor_questions"]) >= 5


def test_baseline_a_scores():
    gt = load_ground_truth()
    out_a = run_baseline_a_manual()
    score_a = score_approach(out_a, gt)
    assert score_a["status"] == "OK"
    assert score_a["PLR"] == 0.0
    assert score_a["EP"] == "N/A"  # No evidence claims generated by manual


def test_baseline_b_security_gate_blocked():
    gt = load_ground_truth()
    out_b = run_baseline_b_generic_ai()
    score_b = score_approach(out_b, gt)
    # Generic AI leaked restricted secret key -> Must be BLOCKED
    assert score_b["status"] == "BLOCKED"
    assert score_b["PLR"] > 0
    assert score_b["BCI"] is None


def test_batonbench_e2e_run():
    result = run_batonbench()
    assert "scores" in result
    assert len(result["scores"]) == 3

    scores = result["scores"]
    baton_score = scores[2]
    assert baton_score["approach"] == "C_BATON"
    assert baton_score["status"] == "OK"
    assert baton_score["PLR"] == 0.0  # Zero leakage!
    assert baton_score["BCI"] is not None
    assert baton_score["BCI"] > 50.0

    # Verify Markdown Table has Table 1 formatting
    table = result["markdown_table"]
    assert "Table 1: BatonBench Comparative Evaluation Results" in table
    assert "BLOCKED" in table
    assert "BATON Evidence-First" in table
